data Line = Line {
    lineNumber :: Int,
    lineContent :: Sentence,
    justification :: String,
    refLines :: Maybe (Int, Int)
}
-- a proof, inside haskell, is just a list of lines. That's all Haskell knows about proofs. 

getRefLines :: Maybe (Int, Int) -> (Int, Int)
getRefLines rfLines = 
    case rfLines of
        Nothing -> (0, 0)
        Just (i, j) -> (i, j)

lineToDatalog :: Line -> String
lineToDatalog line = 
    let (i, j) = getRefLines (refLines line) in
        "Line(" ++ show (lineNumber line) ++ ", " ++
        sentenceToDatalog (lineContent line) ++ ", " ++ 
        "\"" ++ justification line ++ "\", " ++
        show i ++ ", " ++ 
        show j ++ ").\n"

proofToDatalog :: Sentence -> [Line] -> String
proofToDatalog proofGoal proofLines =
    "Goal(" ++ 
    sentenceToDatalog proofGoal ++ 
    ").\n\n" ++
    concatMap lineToDatalog proofLines
    
compileDatalogProof :: String -> Sentence -> Logic -> [Line] -> IO ()
compileDatalogProof proofName proofGoal proofLogic proofLines =
    withFile ("autogenerated_proofs/" ++ logicName proofLogic ++ "/" ++ proofName ++ "/" ++ proofName ++ ".dl") WriteMode $ \h -> do
        hSetEncoding h utf8
        hPutStr h ("#include \"../../../datalog_engines/" ++ (logicName proofLogic) ++ ".dl\"\n\n")
        hPutStr h (proofToDatalog proofGoal proofLines)

kC :: Sentence
kC = (OpNode impl [Atom "P", OpNode impl [Atom "Q", Atom "P"]])
sC :: Sentence
sC = (OpNode impl [OpNode impl [Atom "P", Atom "Q"], OpNode impl [OpNode impl [Atom "P", OpNode impl [Atom "Q", Atom "R"]], OpNode impl [Atom "P", Atom "R"]]])
matchesKC :: Axiom -> Bool
matchesKC axiom = haveSameStructure (axiomContent axiom) kC
matchesSC :: Axiom -> Bool
matchesSC axiom = haveSameStructure (axiomContent axiom) sC

makeKC :: Sentence -> Sentence -> Sentence
makeKC p q = (OpNode impl [p, OpNode impl [q, p]])
makeSC :: Sentence -> Sentence -> Sentence -> Sentence
makeSC p q r = (OpNode impl [OpNode impl [p, q], OpNode impl [OpNode impl [p, OpNode impl [q, r]], OpNode impl [p, r]]])

